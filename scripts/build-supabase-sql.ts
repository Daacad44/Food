import { createHash } from 'node:crypto';
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';

// Regenerate after adding a Prisma migration. Never edit existing migration files.
const root = 'prisma/migrations';
const directories = (await readdir(root, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const initial = await readFile(`${root}/${directories[0]}/migration.sql`, 'utf8');
const tables = [...initial.matchAll(/CREATE TABLE "([^"]+)"/g)].map((match) => match[1]);
const literal = (value: string) => "'" + value.replaceAll("'", "''") + "'";
let sql = `-- GENERATED by scripts/build-supabase-sql.ts. Paste the complete file into Supabase SQL Editor.
-- Atomic and repeatable for a fresh database or one managed by these Prisma migrations.
-- Existing unmanaged/partial application tables cause a rollback; no tables are dropped.
BEGIN;
SET LOCAL search_path = public, pg_catalog;
SELECT pg_advisory_xact_lock(hashtext('botan-sql-setup'));
CREATE TABLE IF NOT EXISTS public."_prisma_migrations" (
  "id" VARCHAR(36) PRIMARY KEY,
  "checksum" VARCHAR(64) NOT NULL,
  "finished_at" TIMESTAMPTZ,
  "migration_name" VARCHAR(255) NOT NULL,
  "logs" TEXT,
  "rolled_back_at" TIMESTAMPTZ,
  "started_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "applied_steps_count" INTEGER NOT NULL DEFAULT 0
);
`;
for (const name of directories) {
  const source = await readFile(`${root}/${name}/migration.sql`, 'utf8');
  const checksum = createHash('sha256').update(source).digest('hex');
  // Preserve unrelated public tables: the original constraint migration's RLS loop
  // is limited here to Botan's tables. Its application-table effects are identical.
  const scoped = source.replace(
    "tablename <> '_prisma_migrations'",
    `tablename IN (${tables.map(literal).join(', ')})`,
  );
  sql += `
DO $botan_migration$
BEGIN
  IF EXISTS (SELECT 1 FROM public."_prisma_migrations" WHERE migration_name = ${literal(name)} AND rolled_back_at IS NULL AND finished_at IS NULL) THEN
    RAISE EXCEPTION 'Unfinished migration: ${name}. Resolve it before running setup.';
  ELSIF EXISTS (SELECT 1 FROM public."_prisma_migrations" WHERE migration_name = ${literal(name)} AND rolled_back_at IS NULL AND finished_at IS NOT NULL) THEN
    IF EXISTS (SELECT 1 FROM public."_prisma_migrations" WHERE migration_name = ${literal(name)} AND rolled_back_at IS NULL AND checksum <> ${literal(checksum)}) THEN
      RAISE EXCEPTION 'Migration checksum mismatch: ${name}. No changes applied.';
    END IF;
    RAISE NOTICE 'Already applied: ${name}';
  ELSE
${scoped}
    INSERT INTO public."_prisma_migrations" (id, checksum, finished_at, migration_name, applied_steps_count)
    VALUES (gen_random_uuid()::text, ${literal(checksum)}, now(), ${literal(name)}, 1);
  END IF;
END
$botan_migration$;
`;
}
sql += `
ALTER TABLE public."_prisma_migrations" ENABLE ROW LEVEL SECURITY;
COMMIT;
SELECT migration_name, finished_at FROM public."_prisma_migrations" WHERE rolled_back_at IS NULL ORDER BY migration_name;
`;
await mkdir('supabase', { recursive: true });
await writeFile('supabase/01-schema.sql', sql);
console.log(
  `Generated supabase/01-schema.sql from ${directories.length} immutable Prisma migrations.`,
);
